# Программа определяет конечную точку черепашки после последовательности команд.
# Входные данные:
#   n — количество команд, затем n строк вида "направление расстояние",
#   где направление — север/юг/запад/восток, а расстояние — целое число сантиметров.
# Движение начинается в точке (0, 0):
# Вывод: две целые координаты конечной точки через пробел.

d = {'север':0, 'юг':0, 'запад':0, 'восток':0}
x = int(input())
for i in range(x):
    step = input().split()
    d[step[0]] += int(step[1])
axis_x = d['север']-d['юг']
axis_y = d['восток']-d['запад']
print(axis_y, axis_x)