# Функция f(x) уже определена.
# Программа считывает количество чисел n, затем n значений xi.
# Для каждого xi выводит f(xi), используя кэширование результатов,
# чтобы избежать повторных вычислений и уложиться в ограничение по времени.

z = int(input())
s = {}
for i in range(z):
    y = int(input())
    if y not in s:
        s[y] = (f(y))
    print(*str(s[y]), sep='')



